import {app, BrowserWindow} from 'electron';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {makeFixture} from '../fixture.cjs';
const temporary=fs.mkdtempSync('/tmp/ares-playback-ui-'), profile=path.join(temporary,'profile'), rom=path.join(temporary,'fixture.gb');
fs.mkdirSync(profile);fs.writeFileSync(rom,makeFixture());app.setPath('userData',profile);
Object.assign(process.env,{ARES_PROFILE_DIR:profile,ARES_ROM:rom,ARES_AUTOTEST:'',ARES_DEFAULT_PLUGINS:'0',ARES_SILENT:'1',ARES_BACKGROUND_TEST:'1'});
delete process.env.ARES_DISABLE_PLUGINS;process.argv.push('--no-services');
const host = path.resolve(import.meta.dirname,'../../build_macos/workbench/bin/ares-electron-host');
if (!process.env.ARES_HOST && fs.existsSync(host)) process.env.ARES_HOST = host;
const {sessions} = await import('../dist/main.js');
const until=async check=>{for(let i=0;i<400;i++){try{const result=await check();if(result)return result;}catch{}await new Promise(r=>setTimeout(r,20));}throw new Error('Playback UI timed out');};
const deadline=setTimeout(()=>app.exit(1),20000);
app.on('will-quit',()=>{clearTimeout(deadline);fs.rmSync(temporary,{recursive:true,force:true});});
app.whenReady().then(async()=>{try{
  const window=await until(()=>BrowserWindow.getAllWindows()[0]), js=code=>window.webContents.executeJavaScript(code);
  window.show();window.focus();await until(()=>js("window.stats?.().system==='Game Boy' && !document.querySelector('#video-controls').hidden"));
  await until(()=>js('document.hasFocus()'));
  const rect=await js("document.querySelector('#viewport').getBoundingClientRect().toJSON()");
  const move=(dx=0)=>window.webContents.sendInputEvent({type:'mouseMove',x:Math.round(rect.x+rect.width/2+dx),y:Math.round(rect.y+rect.height/2)});
  move();
  await until(()=>js("document.querySelector('#viewport').matches(':hover') && getComputedStyle(document.querySelector('#video-controls')).opacity==='1'"));
  // Keep native pointer transitions from other test windows from ending this
  // synthetic hover. Pointer-leave cleanup is covered by playback-idle.test.js.
  await js("window.holdTestPointer = event => event.stopImmediatePropagation(); document.querySelector('#viewport').addEventListener('pointerleave', window.holdTestPointer, true); document.querySelector('#viewport').dispatchEvent(new PointerEvent('pointermove', {pointerType:'mouse'}))");
  await until(()=>js("document.querySelector('#viewport').dataset.mouseIdle==='true'"));
  await until(()=>js("document.querySelector('#viewport').dataset.toolbarIdle==='true' && getComputedStyle(document.querySelector('#video-controls')).opacity==='0'"));
  assert.equal(await js("getComputedStyle(document.querySelector('#screen')).cursor"),'none');
  app.focus({steal:true}); window.focus();
  await js("document.querySelector('#screen').focus()");
  window.webContents.sendInputEvent({type:'keyDown',keyCode:'Tab'});window.webContents.sendInputEvent({type:'keyUp',keyCode:'Tab'});
  await until(()=>js("document.querySelector('#video-controls').contains(document.activeElement) && document.activeElement.matches(':focus-visible')"));
  await until(()=>js("getComputedStyle(document.querySelector('#video-controls')).opacity==='1'"));
  await js("document.querySelector('#viewport').removeEventListener('pointerleave', window.holdTestPointer, true)");
  move(30);
  await until(()=>js("document.querySelector('#viewport').dataset.mouseIdle===undefined"));
  assert.notEqual(await js("getComputedStyle(document.querySelector('#screen')).cursor"),'none');
  await sessions.request('session.pause');
  await new Promise(resolve=>setTimeout(resolve,100));
  const before = await sessions.request('session.status'), frames = await js('window.stats().frames');
  await js("document.querySelector('#video-reset').click()");
  await until(async()=>{const state=await sessions.request('session.status');return state.epoch===before.epoch+1&&state.result.paused;});
  await until(async()=>(await js('window.stats().frames'))>frames);
  const resetFrames=await js('window.stats().frames');
  await new Promise(resolve=>setTimeout(resolve,150));
  assert.equal((await sessions.request('session.status')).result.paused,true);
  assert.equal(await js('window.stats().frames'),resetFrames,'reset renders one preview and stays paused');
  console.log('PASS playback toolbar/cursor idle behavior, keyboard accessibility, and visible reset while paused');app.quit();
}catch(error){console.error(error);app.exit(1);}});
