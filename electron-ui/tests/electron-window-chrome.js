import {app, BrowserWindow} from 'electron';
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {makeFixture} from '../fixture.cjs';
const temporary=fs.mkdtempSync('/tmp/ares-playback-ui-'), profile=path.join(temporary,'profile'), rom=path.join(temporary,'fixture.gb');
fs.mkdirSync(profile);fs.writeFileSync(rom,makeFixture());app.setPath('userData',profile);
Object.assign(process.env,{ARES_PROFILE_DIR:profile,ARES_ROM:rom,ARES_AUTOTEST:'',ARES_DEFAULT_PLUGINS:'0',ARES_SILENT:'1',ARES_BACKGROUND_TEST:'1'});
delete process.env.ARES_DISABLE_PLUGINS;process.argv.push('--no-services');
const host = path.resolve(import.meta.dirname,'../../build_macos/workbench/bin/ares-electron-host');
if (!process.env.ARES_HOST && fs.existsSync(host)) process.env.ARES_HOST = host;
const {sessions} = await import('../dist/main.js');
const until=async check=>{for(let i=0;i<400;i++){try{const result=await check();if(result)return result;}catch{}await new Promise(r=>setTimeout(r,20));}throw new Error('Playback UI timed out');};
const deadline=setTimeout(()=>app.exit(1),30000);
app.on('will-quit',()=>{clearTimeout(deadline);fs.rmSync(temporary,{recursive:true,force:true});});
app.whenReady().then(async()=>{try{
  const window=await until(()=>BrowserWindow.getAllWindows()[0]), js=code=>window.webContents.executeJavaScript(code);
  window.show();window.focus();await until(()=>js("window.stats?.().system==='Game Boy' && !document.querySelector('#video-controls').hidden"));
  await until(()=>js('document.hasFocus()'));
  await until(()=>js("document.querySelector('#window-game-title').textContent==='fixture'"));
  await js("(async()=>{window.testWorkspace = (await import('./dist/browser/workspace/shell.js')).workspace})()");
  await js('window.testWorkspace.ready');
  assert.equal(await js('document.body.dataset.titlebar'),'overlay');
  assert.equal(await js("getComputedStyle(document.querySelector('#window-title-content')).display"),'none');
  if(process.platform==='darwin') assert.equal(await js("document.querySelector('#viewport').getBoundingClientRect().top"),0);
  assert.equal(window.getTitle(),'fixture — ares');
  await js('window.testWorkspace.setEditing(true)');
  assert.equal(await js('document.body.dataset.titlebar'),'visible');
  if(process.platform==='darwin') {
    assert.equal(await js("document.querySelector('#window-drag-region').getBoundingClientRect().height"),28);
    assert.ok(await js("document.querySelector('.area-toolbar').getBoundingClientRect().top>=28"));
  }
  await until(()=>js("document.querySelector('#window-system-icon').naturalWidth>0"));
  await js('window.testWorkspace.setEditing(false);window.testWorkspace.split("video","y")');
  assert.equal(await js('document.body.dataset.titlebar'),'overlay');
  if(process.platform==='darwin') assert.equal(await js("document.querySelector('#viewport').getBoundingClientRect().top"),0);
  assert.equal(await js("[...document.querySelectorAll('.area-toolbar')].every(e=>getComputedStyle(e).display==='none')"),true);
  assert.equal(await js("document.querySelector('.split-divider').getBoundingClientRect().height"),5);
  await js('window.testWorkspace.setEditing(true);window.testWorkspace.setEditing(false)');
  assert.equal(await js("[...document.querySelectorAll('.area-toolbar')].every(e=>getComputedStyle(e).display==='none')"),true);
  await js('window.testWorkspace.reset();window.testWorkspace.split("video","x")');
  assert.equal(await js('document.body.dataset.titlebar'),'visible');
  if(process.platform==='darwin') assert.equal(await js("document.querySelector('#viewport').getBoundingClientRect().top"),28);
  assert.ok(await js("document.querySelector('.split-divider').getBoundingClientRect().height>0"));
  await js('window.testWorkspace.reset();window.testWorkspace.split("video","y");window.testWorkspace.selectPanel(window.testWorkspace.snapshot().root.children[1].id,"video")');
  assert.equal(await js('document.body.dataset.titlebar'),'visible');
  await js('document.body.dataset.fullscreen="true"');
  if(process.platform==='darwin') assert.equal(await js("getComputedStyle(document.querySelector('#window-drag-region')).display"),'none');
  assert.equal(await js("getComputedStyle(document.querySelector('#workspace')).paddingTop"),'0px');
  console.log('PASS dynamic game/system header, top-video layouts, clean dividers after editing, title-bar safe area and fullscreen layout');app.quit();
}catch(error){console.error(error);app.exit(1);}});
